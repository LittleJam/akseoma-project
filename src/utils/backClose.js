import { useEffect, useRef } from 'react';

// «Назад» закрывает верхний слой, а не выходит из приложения.
//
// В установленном PWA кнопок браузера нет: назад — это системная кнопка на
// Android и свайп от края на iOS. Гайдлайны требуют от них того же, что и от
// крестика: сначала снимается то, что открыто поверх, по одному слою за жест,
// и только с пустого экрана приложение закрывается.
//
// Разделы и открытая заметка живут в адресе — у них история своя. Остальным
// слоям (окна, просмотрщик картинок, раскрытый переключатель проектов) адрес
// не нужен, поэтому на время жизни они добавляют в историю пустую запись:
// системный «назад» съедает её и закрывает слой.

// Открытые слои: верхний — последний. Реагирует только он, иначе один жест
// закрывал бы сразу и картинку, и редактор под ней
const layers = [];

// Сколько записей мы сняли сами, закрывая слой из интерфейса. Свой back()
// приходит тем же событием popstate, что и жест пользователя, и без счётчика
// закрытие картинки крестиком закрывало бы заодно и окно под ней
let selfPops = 0;

let listening = false;

const handlePop = () => {
  if (selfPops > 0) {
    selfPops -= 1;
    return;
  }

  const top = layers[layers.length - 1];
  if (!top) return;

  top.closedByBack = true;
  top.close();
};

// Подписка одна на приложение, а не по слою: только так «наш» back() удаётся
// посчитать ровно один раз
const listen = () => {
  if (listening) return;
  window.addEventListener('popstate', handlePop);
  listening = true;
};

// enabled — открыт ли слой; onClose вызывается, когда «назад» его закрыл
export const useBackClose = (enabled, onClose) => {
  // Обработчик читаем из ссылки: слой не должен переоткрывать запись в истории
  // только потому, что родитель отдал новую функцию
  const onCloseRef = useRef(onClose);
  onCloseRef.current = onClose;

  useEffect(() => {
    if (!enabled) return;

    listen();
    const layer = { closedByBack: false, close: () => onCloseRef.current?.() };
    layers.push(layer);
    window.history.pushState({ overlay: true }, '');

    return () => {
      const index = layers.indexOf(layer);
      if (index !== -1) layers.splice(index, 1);

      if (layer.closedByBack) return;

      // Слой закрыли из интерфейса — свою запись снимаем сами, иначе первый
      // «назад» после закрытия уходил бы в пустоту и выглядел как зависание.
      //
      // Но не в этот же миг: закрытие слоя часто и есть переход. Выбор проекта
      // закрывает переключатель и меняет адрес борда, и если снять запись
      // сразу, «назад» уедет по ней обратно на прежний проект — выбор
      // отменялся бы сам собой. Микрозадача ждёт, пока приложение допишет
      // адрес, и запись снимается только если наверху истории всё ещё наша
      Promise.resolve().then(() => {
        if (window.history.state?.overlay) {
          selfPops += 1;
          window.history.back();
        }
      });
    };
  }, [enabled]);
};
